import { test, expect } from '@playwright/test'

test('管理员可以诊断网关并预览授权字段', async ({ page }) => {
  await page.route('**/api/v1/**', async route => {
    const url = new URL(route.request().url())
    if (url.pathname.endsWith('/auth/login')) return route.fulfill({ json: { access_token: 'test-token' } })
    if (url.pathname.endsWith('/auth/me')) return route.fulfill({ json: { username: 'admin', roles: ['admin'], tenant_id: 'default', is_active: true } })
    if (url.pathname.endsWith('/data-sources')) return route.fulfill({ json: [{ id: 'sqlite-demo', name: 'SQLite Demo', backend: 'sqlite' }] })
    if (url.pathname.endsWith('/tasks')) return route.fulfill({ json: [] })
    if (url.pathname.endsWith('/data-gateways')) return route.fulfill({ json: [{ id: 'sqlite-demo', name: 'SQLite Demo', backend: 'sqlite', dialect: 'sqlite', readonly: true }] })
    if (url.pathname.endsWith('/data-gateways/sqlite-demo/health')) return route.fulfill({ json: { status: 'healthy', message: '连接成功', latency_ms: 4 } })
    if (url.pathname.endsWith('/data-gateways/sqlite-demo/test')) return route.fulfill({ json: { status: 'healthy', message: '连接成功', latency_ms: 3 } })
    if (url.pathname.endsWith('/data-gateways/sqlite-demo/schema')) return route.fulfill({ json: { gateway_id: 'sqlite-demo', tables: { sales: ['region', 'amount'] } } })
    if (url.pathname.endsWith('/data-gateways/sqlite-demo/preview')) return route.fulfill({ json: { columns: ['region', 'amount'], rows: [['华东', 120]], row_count: 1, truncated: false, operation_id: 'op-1' } })
    return route.fulfill({ status: 404, json: { detail: 'not mocked' } })
  })

  await page.goto('/')
  await page.getByPlaceholder('用户名').fill('admin')
  await page.getByPlaceholder('密码').fill('local-test-password')
  await page.getByRole('button', { name: '登录' }).click()
  await page.getByRole('button', { name: /数据网关/ }).click()
  await expect(page.getByRole('heading', { name: '数据网关' })).toBeVisible()
  await expect(page.getByText('正常')).toBeVisible()
  await page.getByRole('button', { name: '读取 Schema' }).click()
  await expect(page.getByText('amount', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: '预览数据' }).click()
  await expect(page.getByRole('cell', { name: '华东' })).toBeVisible()
  await expect(page.getByRole('cell', { name: '120' })).toBeVisible()
  await page.setViewportSize({ width: 390, height: 844 })
  await expect(page.getByRole('heading', { name: '数据网关' })).toBeVisible()
  const overflow = await page.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  expect(overflow).toBe(false)
})
