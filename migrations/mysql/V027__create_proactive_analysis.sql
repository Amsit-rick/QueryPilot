CREATE TABLE IF NOT EXISTS proactive_analysis_plans (
  id CHAR(36) PRIMARY KEY,
  tenant_id VARCHAR(64) NOT NULL,
  owner_id VARCHAR(128) NOT NULL,
  question TEXT NOT NULL,
  datasource_id VARCHAR(128) NOT NULL,
  interval_minutes INT NOT NULL,
  max_runs_per_day INT NOT NULL,
  daily_budget_usd DECIMAL(12,6) NOT NULL,
  require_approval BOOLEAN NOT NULL DEFAULT TRUE,
  state VARCHAR(16) NOT NULL DEFAULT 'draft',
  next_run_at DATETIME NULL,
  last_run_at DATETIME NULL,
  last_task_id CHAR(36) NULL,
  runs_today INT NOT NULL DEFAULT 0,
  cost_today_usd DECIMAL(12,6) NOT NULL DEFAULT 0,
  budget_date DATE NULL,
  lease_token CHAR(36) NULL,
  lease_expires_at DATETIME NULL,
  created_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_proactive_plans_owner (tenant_id, owner_id, created_at),
  INDEX idx_proactive_plans_due (state, next_run_at, lease_expires_at),
  CONSTRAINT chk_proactive_plan_state CHECK (state IN ('draft','active','paused','closed')),
  CONSTRAINT chk_proactive_plan_interval CHECK (interval_minutes >= 1),
  CONSTRAINT chk_proactive_plan_runs CHECK (max_runs_per_day >= 1),
  CONSTRAINT chk_proactive_plan_budget CHECK (daily_budget_usd >= 0)
) CHARACTER SET utf8mb4;

CREATE TABLE IF NOT EXISTS proactive_analysis_runs (
  id CHAR(36) PRIMARY KEY,
  plan_id CHAR(36) NOT NULL,
  tenant_id VARCHAR(64) NOT NULL,
  owner_id VARCHAR(128) NOT NULL,
  scheduled_for DATETIME NOT NULL,
  status VARCHAR(24) NOT NULL,
  task_id CHAR(36) NULL,
  trace_id VARCHAR(128) NULL,
  error_code VARCHAR(64) NULL,
  estimated_cost_usd DECIMAL(12,6) NOT NULL DEFAULT 0,
  started_at DATETIME NOT NULL,
  completed_at DATETIME NOT NULL,
  INDEX idx_proactive_runs_plan (tenant_id, owner_id, plan_id, started_at),
  INDEX idx_proactive_runs_task (tenant_id, task_id),
  CONSTRAINT chk_proactive_run_status CHECK (status IN ('completed','approval_required','failed','skipped_budget'))
) CHARACTER SET utf8mb4;
