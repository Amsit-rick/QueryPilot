from typing import Protocol
from app.domain.data_gateway import *
class DataGateway(Protocol):
    descriptor: GatewayDescriptor; capabilities: GatewayCapabilities
    def test_connection(self)->GatewayHealth: ...
    def schema(self)->dict[str,list[str]]: ...
    def schema_details(self)->GatewaySchemaDetails: ...
    def estimate_cost(self, request: GatewayQuery)->GatewayCostEstimate: ...
    def preview(self,table:str,limit:int=20,offset:int=0)->GatewayResult: ...
    def query(self,request:GatewayQuery)->GatewayResult: ...
    def cancel(self,operation_id:str)->bool: ...
    def health(self)->GatewayHealth: ...
